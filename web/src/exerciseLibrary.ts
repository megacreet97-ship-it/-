export function compareCategories(a: string, b: string): number {
  const ia = EXERCISE_CATEGORIES.indexOf(a)
  const ib = EXERCISE_CATEGORIES.indexOf(b)
  if (ia === -1 && ib === -1) return a.localeCompare(b, 'ru')
  if (ia === -1) return 1
  if (ib === -1) return -1
  return ia - ib
}
